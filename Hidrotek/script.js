let typewriterInterval = null;
let typewriterTimeout = null;

function resetTypewriter() {
    const typewriterElement = document.getElementById('typewriter');
    if (!typewriterElement) return;

    // Clear any active typing intervals or timeouts
    clearInterval(typewriterInterval);
    clearTimeout(typewriterTimeout);

    const words = translations[currentLang]["typewriter-words"] || [];
    let wordIndex = 0;
    let charIndex = 0;
    let isDeleting = false;
    typewriterElement.textContent = '';

    function type() {
        const currentWord = words[wordIndex] || '';
        if (isDeleting) {
            typewriterElement.textContent = currentWord.substring(0, charIndex - 1);
            charIndex--;
        } else {
            typewriterElement.textContent = currentWord.substring(0, charIndex + 1);
            charIndex++;
        }

        let typingSpeed = isDeleting ? 40 : 80;

        if (!isDeleting && charIndex === currentWord.length) {
            isDeleting = true;
            typingSpeed = 2500; // Pause at full word
        } else if (isDeleting && charIndex === 0) {
            isDeleting = false;
            wordIndex = (wordIndex + 1) % words.length;
            typingSpeed = 500; // Pause before typing next word
        }

        typewriterTimeout = setTimeout(type, typingSpeed);
    }

    type();
}

// ===== Swipe gestures for Mobile Lightbox =====
let touchStartX = 0;
let touchEndX = 0;

const lightboxEl = document.getElementById('lightbox');
if (lightboxEl) {
    lightboxEl.addEventListener('touchstart', (e) => {
        touchStartX = e.changedTouches[0].screenX;
    }, { passive: true });

    lightboxEl.addEventListener('touchend', (e) => {
        touchEndX = e.changedTouches[0].screenX;
        handleSwipeGesture(e);
    }, { passive: true });
}

function handleSwipeGesture(event) {
    const swipeThreshold = 50;
    const diffX = touchStartX - touchEndX;

    if (Math.abs(diffX) > swipeThreshold) {
        if (diffX > 0) {
            // Swiped left -> Next image (or previous depending on RTL/LTR)
            navigateLightbox(event, document.documentElement.dir === 'rtl' ? -1 : 1);
        } else {
            // Swiped right -> Previous image
            navigateLightbox(event, document.documentElement.dir === 'rtl' ? 1 : -1);
        }
    }
}

